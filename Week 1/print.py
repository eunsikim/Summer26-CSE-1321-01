def main():
    # To declare a variable
    # we define an identifier/name
    # and assign a value to it
    x = 5 # `=` is not equal, instead is "assignment"

    greet = "Hello World"

    print("Hello World")
    print(x)
    print(greet)

    # We can modify a variable's value
    # by reassigning it a new value
    x = 6

    print(x)

if __name__ == "__main__":
    main()