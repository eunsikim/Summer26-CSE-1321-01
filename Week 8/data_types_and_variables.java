public class data_types_and_variables {
    public static void main(String[] args) {
        // Integer types:
        byte age = 30;
        short year = 32767;
        int ship_weight = 2147483647;
        long distance = 2147483647;

        // Character type:
        char c = ' ';

        // Boolean type:
        boolean has_studied = true; // Literal booleans are: `true` or `false`

        // Decimal types:
        float pi = 3.14f;
        double e = 2.71828;
    }
}
